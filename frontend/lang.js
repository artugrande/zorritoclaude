/* ── Core apply function ─────────────────────────────────────────── */
function zorritoSetLang(lang) {
  if (!ZORRITO_T[lang]) return;
  try { localStorage.setItem('zorrito-lang', lang); } catch (_) {}
  document.documentElement.lang = lang;

  const t = ZORRITO_T[lang];

  // Swap all translated text/html/placeholder nodes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t[el.dataset.i18n];
    if (v !== undefined) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const v = t[el.dataset.i18nHtml];
    if (v !== undefined) el.innerHTML = v;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const v = t[el.dataset.i18nPlaceholder];
    if (v !== undefined) el.placeholder = v;
  });

  // Sync native select (docs/stats pages)
  const sel = document.getElementById('lang-select');
  if (sel) sel.value = lang;

  // Sync custom lang picker label (all pages)
  const label = document.getElementById('lang-label');
  if (label) {
    const labels = { en: '🌐 EN', es: '🌐 ES', pt: '🌐 PT' };
    label.textContent = labels[lang] || '🌐 EN';
  }

  // Page title
  const isDocsPage   = !!document.querySelector('body.docs-page');
  const isAgentPage  = document.title.includes('Agent');
  const isBuildPage  = document.title.includes('Building');
  if (lang === 'es') {
    if (isBuildPage)     document.title = 'Zorrito — Construir en Celo';
    else if (isAgentPage) document.title = 'Zorrito — Panel del Agente';
    else if (isDocsPage) document.title = 'Zorrito — Cómo Funciona';
    else                 document.title = 'Zorrito — Lotería Sin Pérdidas';
  } else if (lang === 'pt') {
    if (isBuildPage)     document.title = 'Zorrito — Construir na Celo';
    else if (isAgentPage) document.title = 'Zorrito — Painel do Agente';
    else if (isDocsPage) document.title = 'Zorrito — Como Funciona';
    else                 document.title = 'Zorrito — Loteria Sem Perdas';
  } else {
    if (isBuildPage)     document.title = 'Zorrito — Building on Celo';
    else if (isAgentPage) document.title = 'Zorrito — Agent Dashboard';
    else if (isDocsPage) document.title = 'Zorrito — How It Works';
    else                 document.title = 'Zorrito — No-Loss Lottery';
  }
}

/* ── Auto-apply saved preference on load ────────────────────────── */
(function () {
  try {
    const saved = localStorage.getItem('zorrito-lang') || 'en';
    zorritoSetLang(saved);
  } catch (_) {
    zorritoSetLang('en');
  }
})();
